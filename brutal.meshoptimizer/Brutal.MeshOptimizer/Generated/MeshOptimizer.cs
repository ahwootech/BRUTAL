        ///   </para>
        ///   <para>
        ///     The formula that uses the apex is slightly more accurate but needs the apex; if you are already using bounding sphere
        ///     to do frustum/occlusion culling, the formula that doesn't use the apex may be preferable (for derivation see
        ///     Real-Time Rendering 4th Edition, section 19.3).
        ///   </para>
        ///   <para>
        ///     vertex_positions should have float3 position in the first 12 bytes of each vertex
        ///     vertex_count should specify the number of vertices in the entire mesh, not cluster or meshlet
        ///     indices should have at most 256 unique vertex indices
        ///     index_count/3 and triangle_count must not exceed implementation limits (&lt;= 512)
        ///   </para>
        /// </remarks>
        [LibraryImport("meshoptimizer", EntryPoint = "meshopt_computeClusterBounds")]
        public static partial MeshOptBounds ComputeClusterBounds(
            Ptr<int> indices,
            long indexCount,
            Ptr<float> vertexPositions,
            long vertexCount,
            ByteSize64 vertexPositionsStride
        );


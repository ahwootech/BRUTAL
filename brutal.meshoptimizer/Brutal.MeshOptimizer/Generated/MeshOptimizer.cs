        /// <summary>
        ///   Generates a vertex remap table from the vertex buffer and an optional index buffer and returns number of unique vertices
        ///   As a result, all vertices that are binary equivalent map to the same (new) location, with no gaps in the resulting sequence.
        ///   Resulting remap table maps old vertices to new vertices and can be used in meshopt_remapVertexBuffer/meshopt_remapIndexBuffer.
        ///   Note that binary equivalence considers all vertex_size bytes, including padding which should be zero-initialized.
        /// </summary>
        /// <remarks>
        ///   <para>
        ///     destination must contain enough space for the resulting remap table (vertex_count elements)
        ///     indices can be NULL if the input is unindexed
        ///   </para>
        /// </remarks>
        [LibraryImport("meshoptimizer", EntryPoint = "meshopt_generateVertexRemap")]
        public static partial ByteSize64 GenerateVertexRemap(
            Ptr<int> destination,
            Ptr<int> indices,
            long indexCount,
            Ptr vertices,
            long vertexCount,
            ByteSize64 vertexSize
        );

        /// <summary>
        ///   Generates a vertex remap table from multiple vertex streams and an optional index buffer and returns number of unique vertices
        ///   As a result, all vertices that are binary equivalent map to the same (new) location, with no gaps in the resulting sequence.
        ///   Resulting remap table maps old vertices to new vertices and can be used in meshopt_remapVertexBuffer/meshopt_remapIndexBuffer.
        ///   To remap vertex buffers, you will need to call meshopt_remapVertexBuffer for each vertex stream.
        ///   Note that binary equivalence considers all size bytes in each stream, including padding which should be zero-initialized.
        /// </summary>
        /// <remarks>
        ///   <para>
        ///     destination must contain enough space for the resulting remap table (vertex_count elements)
        ///     indices can be NULL if the input is unindexed
        ///     stream_count must be &lt;= 16
        ///   </para>
        /// </remarks>
        [LibraryImport("meshoptimizer", EntryPoint = "meshopt_generateVertexRemapMulti")]
        public static partial ByteSize64 GenerateVertexRemapMulti(
            Ptr<int> destination,
            Ptr<int> indices,
            long indexCount,
            long vertexCount,
            Ptr<MeshOptStream> streams,
            long streamCount
        );

        /// <summary>
        ///   Generates a vertex remap table from the vertex buffer and an optional index buffer and returns number of unique vertices
        ///   As a result, all vertices that are equivalent map to the same (new) location, with no gaps in the resulting sequence.
        ///   Equivalence is checked in two steps: vertex positions are compared for equality, and then the user-specified equality function is called (if provided).
        ///   Resulting remap table maps old vertices to new vertices and can be used in meshopt_remapVertexBuffer/meshopt_remapIndexBuffer.
        /// </summary>
        /// <remarks>
        ///   <para>
        ///     destination must contain enough space for the resulting remap table (vertex_count elements)
        ///     indices can be NULL if the input is unindexed
        ///     vertex_positions should have float3 position in the first 12 bytes of each vertex
        ///     callback can be NULL if no additional equality check is needed; otherwise, it should return 1 if vertices with specified indices are equivalent and 0 if they are not
        ///   </para>
        /// </remarks>
        [LibraryImport("meshoptimizer", EntryPoint = "meshopt_generateVertexRemapCustom")]
        public static unsafe partial ByteSize64 GenerateVertexRemapCustom(
            Ptr<int> destination,
            Ptr<int> indices,
            long indexCount,
            Ptr<float> vertexPositions,
            long vertexCount,
            ByteSize64 vertexPositionsStride,
            delegate* unmanaged[Cdecl]<Ptr, int, int, int> callback,
            Ptr context
        );


namespace Brutal.VulkanApi
{
    /// <summary>
    ///     <see href="https://registry.khronos.org/vulkan/specs/1.3-extensions/man/html/VkQueryPipelineStatisticFlagBits.html">VkQueryPipelineStatisticFlagBits</see> - Bitmask specifying queried pipeline statistics
    /// </summary>
    /// <remarks>
    ///     <para>
    ///         Bits which <i>can</i> be set in
    ///         <c>VkQueryPoolCreateInfo::pipelineStatistics</c> for query pools and in
    ///         <c>VkCommandBufferInheritanceInfo::pipelineStatistics</c> for secondary
    ///         command buffers, individually enabling pipeline statistics counters, are:
    ///     </para>
    ///     <code>
    ///         // Provided by VK_VERSION_1_0
    ///         typedef enum VkQueryPipelineStatisticFlagBits {
    ///             VK_QUERY_PIPELINE_STATISTIC_INPUT_ASSEMBLY_VERTICES_BIT = 0x00000001,
    ///             VK_QUERY_PIPELINE_STATISTIC_INPUT_ASSEMBLY_PRIMITIVES_BIT = 0x00000002,
    ///             VK_QUERY_PIPELINE_STATISTIC_VERTEX_SHADER_INVOCATIONS_BIT = 0x00000004,
    ///             VK_QUERY_PIPELINE_STATISTIC_GEOMETRY_SHADER_INVOCATIONS_BIT = 0x00000008,
    ///             VK_QUERY_PIPELINE_STATISTIC_GEOMETRY_SHADER_PRIMITIVES_BIT = 0x00000010,
    ///             VK_QUERY_PIPELINE_STATISTIC_CLIPPING_INVOCATIONS_BIT = 0x00000020,
    ///             VK_QUERY_PIPELINE_STATISTIC_CLIPPING_PRIMITIVES_BIT = 0x00000040,
    ///             VK_QUERY_PIPELINE_STATISTIC_FRAGMENT_SHADER_INVOCATIONS_BIT = 0x00000080,
    ///             VK_QUERY_PIPELINE_STATISTIC_TESSELLATION_CONTROL_SHADER_PATCHES_BIT = 0x00000100,
    ///             VK_QUERY_PIPELINE_STATISTIC_TESSELLATION_EVALUATION_SHADER_INVOCATIONS_BIT = 0x00000200,
    ///             VK_QUERY_PIPELINE_STATISTIC_COMPUTE_SHADER_INVOCATIONS_BIT = 0x00000400,
    ///             // Provided by VK_EXT_mesh_shader
    ///             VK_QUERY_PIPELINE_STATISTIC_TASK_SHADER_INVOCATIONS_BIT_EXT = 0x00000800,
    ///             // Provided by VK_EXT_mesh_shader
    ///             VK_QUERY_PIPELINE_STATISTIC_MESH_SHADER_INVOCATIONS_BIT_EXT = 0x00001000,
    ///             // Provided by VK_HUAWEI_cluster_culling_shader
    ///             VK_QUERY_PIPELINE_STATISTIC_CLUSTER_CULLING_SHADER_INVOCATIONS_BIT_HUAWEI = 0x00002000,
    ///         } VkQueryPipelineStatisticFlagBits;
    ///     </code>
    /// </remarks>
    [Flags]
    public enum VkQueryPipelineStatisticFlags : int
    {
        /// No flags set.
        None = 0,

        /// <summary>
        ///     <c>InputAssemblyVerticesBit</c> specifies that queries managed by the pool will count the number of vertices processed by the <see href="https://registry.khronos.org/vulkan/specs/latest/html/vkspec.html#drawing">input assembly^</see> stage. Vertices corresponding to incomplete primitives may: contribute to the count.
        /// </summary>
        InputAssemblyVerticesBit = 0x00000001,

        /// <summary>
        ///     <c>InputAssemblyPrimitivesBit</c>  specifies that queries managed by the pool will count the number of primitives processed by the <see href="https://registry.khronos.org/vulkan/specs/latest/html/vkspec.html#drawing">input assembly^</see> stage. If primitive restart is enabled, restarting the primitive topology has no effect on the count. Incomplete primitives may: be counted.
        /// </summary>
        InputAssemblyPrimitivesBit = 0x00000002,

        /// <summary>
        ///     <c>VertexShaderInvocationsBit</c>  specifies that queries managed by the pool will count the number of vertex shader invocations. This counter&apos;s value is incremented each time a vertex shader is <see href="https://registry.khronos.org/vulkan/specs/latest/html/vkspec.html#shaders-vertex-execution">invoked^</see>.
        /// </summary>
        VertexShaderInvocationsBit = 0x00000004,

        /// <summary>
        ///     <c>GeometryShaderInvocationsBit</c>  specifies that queries managed by the pool will count the number of geometry shader invocations. This counter&apos;s value is incremented each time a geometry shader is <see href="https://registry.khronos.org/vulkan/specs/latest/html/vkspec.html#shaders-geometry-execution">invoked^</see>. In the case of <see href="https://registry.khronos.org/vulkan/specs/latest/html/vkspec.html#geometry-invocations">instanced geometry shaders^</see>, the geometry shader invocations count is incremented for each separate instanced invocation.
        /// </summary>
        GeometryShaderInvocationsBit = 0x00000008,

        /// <summary>
        ///     <c>GeometryShaderPrimitivesBit</c>  specifies that queries managed by the pool will count the number of primitives generated by geometry shader invocations. The counter&apos;s value is incremented each time the geometry shader emits a primitive. Restarting primitive topology using the SPIR-V instructions <c>OpEndPrimitive</c> or <c>OpEndStreamPrimitive</c> has no effect on the geometry shader output primitives count.
        /// </summary>
        GeometryShaderPrimitivesBit = 0x00000010,

        /// <summary>
        ///     <c>ClippingInvocationsBit</c> specifies that queries managed by the pool will count the number of primitives processed by the <see href="https://registry.khronos.org/vulkan/specs/latest/html/vkspec.html#vertexpostproc-clipping">Primitive Clipping^</see> stage of the pipeline. The counter&apos;s value is incremented each time a primitive reaches the primitive clipping stage.
        /// </summary>
        ClippingInvocationsBit = 0x00000020,

        /// <summary>
        ///     <c>ClippingPrimitivesBit</c> specifies that queries managed by the pool will count the number of primitives output by the <see href="https://registry.khronos.org/vulkan/specs/latest/html/vkspec.html#vertexpostproc-clipping">Primitive Clipping^</see> stage of the pipeline. The counter&apos;s value is incremented each time a primitive passes the primitive clipping stage. The actual number of primitives output by the primitive clipping stage for a particular input primitive is implementation-dependent but <i>must</i> satisfy the following conditions:
        /// </summary>
        ClippingPrimitivesBit = 0x00000040,

        /// <summary>
        ///     <c>FragmentShaderInvocationsBit</c>  specifies that queries managed by the pool will count the number of fragment shader invocations. The counter&apos;s value is incremented each time the fragment shader is <see href="https://registry.khronos.org/vulkan/specs/latest/html/vkspec.html#fragops-shader">invoked^</see>.
        /// </summary>
        FragmentShaderInvocationsBit = 0x00000080,

        /// <summary>
        ///     <c>TessellationControlShaderPatchesBit</c>  specifies that queries managed by the pool will count the number of patches processed by the tessellation control shader. The counter&apos;s value is incremented once for each patch for which a tessellation control shader is <see href="https://registry.khronos.org/vulkan/specs/latest/html/vkspec.html#shaders-tessellation-control-execution">invoked^</see>.
        /// </summary>
        TessellationControlShaderPatchesBit = 0x00000100,

        /// <summary>
        ///     <c>TessellationEvaluationShaderInvocationsBit</c>  specifies that queries managed by the pool will count the number of invocations of the tessellation evaluation shader. The counter&apos;s value is incremented each time the tessellation evaluation shader is <see href="https://registry.khronos.org/vulkan/specs/latest/html/vkspec.html#shaders-tessellation-evaluation-execution">invoked^</see>.
        /// </summary>
        TessellationEvaluationShaderInvocationsBit = 0x00000200,

        /// <summary>
        ///     <c>ComputeShaderInvocationsBit</c>  specifies that queries managed by the pool will count the number of compute shader invocations. The counter&apos;s value is incremented every time the compute shader is invoked. Implementations may: skip the execution of certain compute shader invocations or execute additional compute shader invocations for implementation-dependent reasons as long as the results of rendering otherwise remain unchanged.  These values are intended to measure relative statistics on one implementation. Various device architectures will count these values differently. Any or all counters may: be affected by the issues described in <see href="https://registry.khronos.org/vulkan/specs/latest/html/vkspec.html#queries-operation-undefined">Query Operation^</see>.   [NOTE]
        /// </summary>
        ComputeShaderInvocationsBit = 0x00000400,

        /// <summary>
        ///     <c>TaskShaderInvocationsBitEXT</c>
        /// </summary>
        TaskShaderInvocationsBitEXT = 0x00000800,

        /// <summary>
        ///     <c>MeshShaderInvocationsBitEXT</c>
        /// </summary>
        MeshShaderInvocationsBitEXT = 0x00001000,

        /// <summary>
        ///     <c>ClusterCullingShaderInvocationsBitHUAWEI</c>
        /// </summary>
        ClusterCullingShaderInvocationsBitHUAWEI = 0x00002000,

        /// <summary>
        ///     <c>FlagBitsMaxEnum</c>
        /// </summary>
        FlagBitsMaxEnum = 0x7FFFFFFF,
    }
}

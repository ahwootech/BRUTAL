    This file is generated by the T4 generator.
    See LString.Format.gen.tt

    IBufferWriter notes, and why didn't we use that?

    It forces a managed API via GetMemory.
    It only has "give me memory of X size or greater" and "Give me at least 1". It cannot
    do "Give me X or smaller" which is more useful for LString so we can be more confident
    in a single TryWrite() call being enough.
    GetSpan can't return an empty span to say "no memory", so all we can do is throw if out of buffer.

    We want to ask for some size we think is enough (e.g. 128 elements) but not run risk of choosing too low. If there's not enough, a smaller might be OK
    but GetSpan can only throw in this case. We could start small and go up and it's possible we only need a tiny amount, say 4 characters, but what smallest size do we choose to start
    because we don't want to TryWrite and request multiple times.

*/
